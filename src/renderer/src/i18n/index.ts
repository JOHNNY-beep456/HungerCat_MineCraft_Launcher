/** 各域分片（同一键冲突时后者覆盖前者，键前缀互不重叠）。 */
const FRAGMENTS: LocaleDict[] = [
  shellMessages,
  homeMessages,
  resourceMessages,
  instanceMessages,
  accountMessages,
  homepageMessages,
  aboutMessages,
  componentMessages,
  customHomeMessages,
  multiplayerMessages
]

/** 合并核心词 + 分片，得到每种语言的最终字典。 */
function buildDicts(): Record<Locale, Record<string, string>> {
  const base: Record<Locale, Record<string, string>> = {
    'zh-CN': { ...zhCN },
    'zh-TW': { ...zhTW },
    en: { ...en }
  }
  for (const frag of FRAGMENTS) {
    for (const loc of Object.keys(frag) as Locale[]) {
      base[loc] = { ...base[loc], ...frag[loc] }
    }
  }
  return base
}

const DICTS = buildDicts()

/** 生成某语言的翻译函数：目标语言 → 简体中文 → 键名。 */
export function createTranslator(locale: Locale): TFunction {
  const dict = DICTS[locale] ?? DICTS[FALLBACK]
  const fallback = DICTS[FALLBACK]
  return (key, vars) => {
    let s = dict[key] ?? fallback[key] ?? key
    if (vars) {
      for (const k of Object.keys(vars)) s = s.split(`{${k}}`).join(String(vars[k]))
    }
    return s
  }
}
