// ---------------------------------------------------------------------------

/** 默认 KEY 的分片（按顺序拼接）。 */
const PARTS = [
  '$2a$10$X3Oi59zph',
  '7PyOAEO/0kyxuQ',
  'mxAOJxOunNaDT3',
  'LJmw2jPzUzZaFCr.'
]

let cached = ''

/** 取出内置的默认 CurseForge KEY（未配置时返回空串）。 */
export function defaultCurseforgeKey(): string {
  if (!cached) cached = PARTS.join('')
  return cached
}
